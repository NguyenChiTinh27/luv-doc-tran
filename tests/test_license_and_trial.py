import os
import sys
import unittest
import tempfile
import time
from pathlib import Path

# Add project root to sys.path
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE_DIR)

from core.license_client import LUVLicenseClient, SECRET_SALT, TRIAL_DURATION_SECONDS


class TestLicenseAndTrial(unittest.TestCase):

    def setUp(self):
        self.test_device = "TEST-DEV-DEVICE-999"
        # Backup trial and license if exist
        self.trial_db = os.path.join(BASE_DIR, "trials_db.json")
        self.lic_file = os.path.join(BASE_DIR, "license.json")
        self.lic_backup = None
        if os.path.exists(self.lic_file):
            with open(self.lic_file, "r", encoding="utf-8") as f:
                self.lic_backup = f.read()

    def tearDown(self):
        # Restore license if backed up
        if self.lic_backup is not None:
            with open(self.lic_file, "w", encoding="utf-8") as f:
                f.write(self.lic_backup)
        elif os.path.exists(self.lic_file):
            os.remove(self.lic_file)

    def test_trial_initialization_and_countdown(self):
        """Verify 48-hour trial is properly initiated and formatted."""
        status = LUVLicenseClient.get_trial_status(self.test_device)
        self.assertTrue(status["is_trial_active"])
        self.assertGreater(status["remaining_seconds"], 0)
        self.assertLessEqual(status["remaining_seconds"], TRIAL_DURATION_SECONDS)
        self.assertIn("giờ", status["remaining_formatted"])

    def test_master_key_validation(self):
        """Verify standard master keys are accepted."""
        valid, msg, details = LUVLicenseClient.verify_key("LUV-PDF-2026-PRO-VN99", "Admin VIP")
        self.assertTrue(valid)
        self.assertIn("Master", details["tier"])

    def test_sha256_key_matching_license_manager_app(self):
        """Verify keys generated by LUV_License_Manager.exe match validation here."""
        import hashlib
        reg = "Công Ty TNHH An Toàn Hóa Chất"
        tier = "Enterprise Lifetime (Vĩnh viễn)"
        expires = "Vĩnh viễn (Lifetime)"

        raw_hash = hashlib.sha256(f"{reg}_{tier}_{expires}_{SECRET_SALT}".encode()).hexdigest().upper()
        prefix = "LUV-ENT"
        key = f"{prefix}-{raw_hash[:4]}-{raw_hash[4:8]}-{raw_hash[8:12]}"

        # Verify in client
        valid, msg, details = LUVLicenseClient.verify_key(key, reg)
        self.assertTrue(valid)
        self.assertEqual(details["tier"], "Doanh nghiệp Vĩnh viễn (Enterprise Lifetime)")

    def test_invalid_key_rejected(self):
        """Verify fake/malformed keys are rejected."""
        valid, msg, _ = LUVLicenseClient.verify_key("INVALID-KEY-1234")
        self.assertFalse(valid)

        valid, msg, _ = LUVLicenseClient.verify_key("")
        self.assertFalse(valid)

    def test_license_activation(self):
        """Verify license activation creates license.json and grants permanent access."""
        key = "LUV-PRO-1122-3344-5566"
        reg = "Test Enterprise Client"
        res = LUVLicenseClient.activate_key(key, reg)

        self.assertTrue(res["is_active"])
        self.assertEqual(res["license_key"], key)

        # Check access
        access = LUVLicenseClient.check_access(self.test_device)
        self.assertTrue(access["has_access"])
        self.assertEqual(access["access_type"], "licensed")


if __name__ == "__main__":
    unittest.main()
